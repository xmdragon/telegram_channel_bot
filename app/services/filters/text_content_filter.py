    async def filter(self, content: str, context: FilterContext) -> FilterResult:
        """执行文本内容过滤"""
        start_time = time.time()
        
        if not content:
            return FilterResult(
                filtered_content="",
                passed=True,
                processing_time_ms=0.0,
                reason="空内容",
                confidence=0.0
            )
        
        try:
            # 执行推广内容过滤
            filtered_content = self._filter_promotional_content(content, context)
            
            # 判断是否被过滤
            was_filtered = len(filtered_content) < len(content)
            passed = not self._is_pure_advertisement(content)
            
            # 生成过滤原因
            reason = ""
            confidence = 0.0
            
            if was_filtered:
                reason = "检测到推广内容"
                confidence = 0.8
            
            if not passed:
                reason = "纯广告内容"
                confidence = 0.9
            
            processing_time = (time.time() - start_time) * 1000
            
            return FilterResult(
                filtered_content=filtered_content,
                passed=passed,
                processing_time_ms=processing_time,
                reason=reason,
                confidence=confidence,
                details={
                    'original_length': len(content),
                    'filtered_length': len(filtered_content),
                    'compression_ratio': len(filtered_content) / max(len(content), 1)
                }
            )
            
        except Exception as e:
            logger.error(f"文本过滤器处理失败: {e}")
            processing_time = (time.time() - start_time) * 1000
            return FilterResult(
                filtered_content=content,
                passed=True,
                processing_time_ms=processing_time,
                reason=f"处理异常: {str(e)}",
                confidence=0.0
            )
    
    def _filter_promotional_content(self, content: str, context: FilterContext) -> str:
        """
        智能过滤推广内容 - 基于规则的版本
        """
        if not content:
            return content
        
        # 保存原始内容
        original_content = content
        
        # 首先移除所有Markdown链接
        content = self._remove_markdown_links(content, context)
        
        # 智能规则过滤
        content = self._smart_rule_filter(content)
        
        return content
    
    def _remove_markdown_links(self, content: str, context: FilterContext) -> str:
        """移除所有Markdown格式的链接，智能处理标签"""
        if not content:
            return content
        
        channel_name = self._extract_channel_name(context)
        lines = content.split('\n')
        filtered_lines = []
        
        for line in lines:
            processed_line = self._process_markdown_line(line, channel_name)
            if processed_line is None:
                continue
            
            # 后处理：清理和过滤无用行
            processed_line = self._post_process_line(processed_line, line)
            if processed_line:
                filtered_lines.append(processed_line)
        
        return '\n'.join(filtered_lines)
    
    def _extract_channel_name(self, context: FilterContext) -> str:
        """提取频道名称"""
        channel_id = context.get_metadata('channel_id')
        if not channel_id or not isinstance(channel_id, str):
            return None
        
        if channel_id.startswith('@'):
            return channel_id[1:].lower()
        
        if channel_id.startswith('-100'):
            known_channels = {
                '-1001153220419': 'dny185',
                '-1001875033283': 'dubai0',
            }
            return known_channels.get(channel_id, '').lower()
        
        return channel_id.lower()
    
    def _process_markdown_line(self, line: str, channel_name: str) -> str:
        """处理包含Markdown链接的行"""
        markdown_pattern = r'\[([^\]]*)\]\(([^\)]+)\)'
        
        if not re.search(markdown_pattern, line):
            return line
        
        def replace_link(match):
            return self._process_single_link(match.group(1), match.group(2), channel_name)
        
        return re.sub(markdown_pattern, replace_link, line)
    
    def _process_single_link(self, link_text: str, link_url: str, channel_name: str) -> str:
        """处理单个链接 - Linus风格：纯函数，无嵌套"""
        # 检查移除条件
        if self._should_remove_link(link_text, link_url, channel_name):
            return ''
        
        # 保留文字部分
        return link_text.strip() if link_text else ''
    
    def _should_remove_link(self, link_text: str, link_url: str, channel_name: str) -> bool:
        """判断是否应该移除链接 - 统一决策逻辑"""
        # 1. 频道相关标签
        if channel_name and link_text and channel_name in link_text.lower():
            logger.debug(f"检测到频道相关标签: {link_text}")
            return True
        
        # 2. 推广关键词
        promo_keywords = [
            '订阅', '订閱', '关注', '關注', '加入', '投稿', 
            '商务', '商務', '联系', '聯繫', '频道', '頻道', 
            'channel', 'group', '失联', '导航', '備用', '官方'
        ]
        
        if link_text:
            for keyword in promo_keywords:
                if keyword in link_text.lower():
                    logger.debug(f"检测到推广关键词 '{keyword}': {link_text}")
                    return True
        
        # 3. 纯符号链接
        if link_text and re.match(r'^[^\w\u4e00-\u9fa5]+$', link_text):
            logger.debug(f"检测到纯符号链接: {link_text}")
            return True
        
        # 4. Telegram链接
        if 't.me' in link_url.lower() or 'telegram' in link_url.lower():
            logger.debug(f"检测到Telegram链接: {link_url[:30]}")
            return True
        
        return False
    
    def _post_process_line(self, processed_line: str, original_line: str) -> str:
        """后处理行：清理格式和过滤无用内容"""
        # 基础清理
        processed_line = re.sub(r'\s+', ' ', processed_line).strip()
        processed_line = re.sub(r'^[:：]\s*', '', processed_line)
        processed_line = re.sub(r'^\|\s*|\s*\|$', '', processed_line)
        processed_line = re.sub(r'\|\s*\|', '|', processed_line)
        
        # 过滤无用行
        if self._is_useless_line(processed_line, original_line):
            return None
        
        return processed_line if processed_line else None
    
    def _is_useless_line(self, processed_line: str, original_line: str) -> bool:
        """判断是否为无用行"""
        # 只含标题的行
        if re.match(r'^[^a-zA-Z]*[^:：]*[:：]\s*$', processed_line) and len(processed_line) < 30:
            logger.info(f"删除只含标题的行: '{original_line[:50]}...'")
            return True
        
        # 引导词行
        guide_words = [
            '查看详情', '订阅频道', '订阅我们', '关注我们', '更多信息',
            '查看更多', '点击查看', '了解更多', '商务合作', '投稿爆料'
        ]
        
        for word in guide_words:
            if processed_line.startswith(word) and re.match(f'^{re.escape(word)}[:：]?\\s*$', processed_line):
                logger.info(f"删除只含引导词的行: '{original_line[:50]}...'")
                return True
        
        # 分隔符行
        if processed_line in ['|', '||', ''] or len(processed_line.strip('| ')) < 3:
            logger.info(f"删除只含分隔符的行: '{original_line[:50]}...'")
            return True
        
        return False
    
    def _smart_rule_filter(self, content: str) -> str:
        """
        智能规则过滤，寻找明确的推广边界
        """
        lines = content.split('\n')
        if len(lines) < 3:
            return content
        
        # 明确的分隔标志
        strong_separators = [
            r'^[-=_—➖]{10,}$',  # 长分隔线
            r'^[📢📣🔔💬❤️🔗]{2,}.*$',  # 多个推广表情
            r'^[-=\*]{3,}\s*$',  # 短分隔线
        ]
        
        # 推广内容的强特征
        strong_promo = [
            r'\[.*\]\(https?://.*\)',  # Markdown链接格式
            r'(?:订阅|關注|投稿|商务|联系).*(?:@|t\.me/)',  # 推广词+链接
            r'https?://(?!(?:t\.me|telegram\.me))',  # 非Telegram链接
            r'^\s*(?:频道|頻道|channel).*(?:@|t\.me/)',  # 频道推广
        ]
        
        # 从后向前查找最明确的分隔点
        best_separator_index = -1
        
        for i in range(len(lines) - 1, max(0, len(lines) - 20), -1):
            line = lines[i].strip()
            
            # 检查是否是强分隔符
            is_strong_separator = any(re.match(p, line) for p in strong_separators)
            
            if is_strong_separator:
                # 验证分隔符后面确实有推广内容
                has_strong_promo = False
                promo_lines = 0
                
                for j in range(i + 1, min(i + 10, len(lines))):
                    if any(re.search(p, lines[j], re.IGNORECASE) for p in strong_promo):
                        has_strong_promo = True
                        promo_lines += 1
                
                # 如果后面有至少2行推广内容，这是一个有效的分隔点
                if has_strong_promo and promo_lines >= 2:
                    best_separator_index = i
                    break
        
        # 如果找到了明确的分隔点，过滤掉分隔符及之后的内容
        if best_separator_index != -1:
            result = '\n'.join(lines[:best_separator_index])
            # 清理尾部空行
            while result.endswith('\n\n'):
                result = result[:-1]
            return result.strip()
        
        return content
    
    def is_promo_line(self, line: str) -> Tuple[bool, int]:
        """
        判断单行是否为推广内容
        
        Returns:
            (是否推广, 置信度分数)
        """
        if not line.strip():
            return False, 0
            
        line_lower = line.lower()
        max_score = 0
        
        # 先检查是否是用户投稿等受保护内容
        if re.match(r'^#(网友|群友|读者|粉丝|用户)投稿', line, re.IGNORECASE):
            return False, 0
        if re.match(r'^#(真实经历|亲身经历|用户分享)', line, re.IGNORECASE):
            return False, 0
            
        # 使用编译后的正则表达式检查推广特征
        for pattern_str, (compiled_pattern, score) in self._compiled_patterns.items():
            if compiled_pattern.search(line):
                max_score = max(max_score, score)
        
        # 使用编译后的保护器检查保护内容
        has_protected_content = False
        for protector_pattern in self._compiled_protectors:
            if protector_pattern.search(line):
                has_protected_content = True
                # 如果包含保护内容，大幅降低推广分数
                if max_score >= 9:
                    max_score = max(0, max_score - 6)  # 降6分
                else:
                    max_score = max(0, max_score - 5)  # 降5分
                break
        
        # 特殊处理：如果包含曝光/爆料等强保护词，即使有链接也不算推广
        strong_protection_words = r'(曝光|爆料|揭露|举报|骗子|黑店|诈骗)'
        if re.search(strong_protection_words, line, re.IGNORECASE):
            # 除非是明确的推广链接（如"订阅频道"）
            if not re.search(r'(订阅|关注|加入).*(频道|channel|@|t\.me)', line, re.IGNORECASE):
                return False, 0  # 强保护，不算推广
                
        return max_score >= 8, max_score  # 提高阈值从7到8，减少误判
    
    def _is_pure_advertisement(self, content: str) -> bool:
        """
        判断是否纯广告内容
        """
        if not content:
            return False
            
        # 过滤后如果几乎没有剩余内容，说明是纯广告
        filtered = self._filter_promotional_content(content, FilterContext())
        
        # 如果过滤后内容为空或者剩余内容太少
        if not filtered.strip():
            return True
            
        # 如果过滤掉了80%以上的内容，认为是广告
        if len(filtered) < len(content) * 0.2:
            return True
            
        return False
    
    def is_commercial_ad(self, content: str) -> bool:
        """检测是否为商业广告"""
        if not content:
            return False
            
        lines = content.split('\n')
        commercial_indicators = 0
        
        # 关键商业指标
        commercial_patterns = [
            r'(营业时间|營業時間|营业中|營業中)',
            r'(店铺地址|店鋪地址|门店地址|門店地址)',
            r'(经营项目|經營項目|主营|主營)',
            r'(优惠|優惠|折扣|打折|特价|特價)',
            r'(微信[:：]|WeChat[:：])',
            r'(电话[:：]|電話[:：]|手机[:：]|手機[:：])',
            r'(接单|接單|下单|下單|订购|訂購)',
            r'(价格|價格|收费|收費|费用|費用)',
        ]
        
        for line in lines:
            for pattern in commercial_patterns:
                if re.search(pattern, line, re.IGNORECASE):
                    commercial_indicators += 1
                    break
        
        # 如果有4个或以上商业指标，判定为商业广告
        return commercial_indicators >= 4
    
